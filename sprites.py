# ⚠️ 重要：出典の dot-illust.net は「非商用なら自由に使っていい」ライセンス。
# 個人利用・実験段階は OK だが、IP 展開・商用化・配布する場合は
# 必ずオリジナルのドット絵に差し替えること。
# 各品種は同じ形状をベースにわずかに装飾を変える（モノクロ 1bit OLED）。
# ============================================================


def _r(s):
    """24 文字パターン (#=ON, .=OFF) を [b0, b1, b2] に変換"""
    b = [0, 0, 0]
    for i, c in enumerate(s[:24]):
        if c == '#':
            b[i >> 3] |= 1 << (7 - (i & 7))
    return b


def _img(*rows):
    return [_r(r) for r in rows]


def _flip(sp):
    """スプライトを左右反転（L→R 生成用）"""
    out = []
    for row in sp:
        v = (row[0] << 16) | (row[1] << 8) | row[2]
        rev = 0
        for i in range(24):
            if (v >> i) & 1:
                rev |= 1 << (23 - i)
        out.append([(rev >> 16) & 0xFF, (rev >> 8) & 0xFF, rev & 0xFF])
    return out


