# mokomoko - sprites.py
# 24×24 ピクセルスプライト（全27枚）
# 形式: 各スプライトは 24 行のリスト、各行 [byte0, byte1, byte2]
#       MSB-first / 1ビット = 1ピクセル / 白=ON(1), 黒=OFF(0)
# ============================================================


def _r(s):
    """24文字パターン (#=ON, .=OFF) を [b0, b1, b2] に変換"""
    b = [0, 0, 0]
    for i, c in enumerate(s[:24]):
        if c == '#':
            b[i >> 3] |= 1 << (7 - (i & 7))
    return b


def _img(*rows):
    return [_r(r) for r in rows]


def _flip(sp):
    """スプライトを左右反転（L→R 生成用）"""
    out = []
    for row in sp:
        v = (row[0] << 16) | (row[1] << 8) | row[2]
        rev = 0
        for i in range(24):
            if (v >> i) & 1:
                rev |= 1 << (23 - i)
        out.append([(rev >> 16) & 0xFF, (rev >> 8) & 0xFF, rev & 0xFF])
    return out


