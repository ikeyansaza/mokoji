#
# ⚠️ 重要：現在のデザインは dot-illust.net 由来の hitsuji.svg ベース。
# 非商用なら利用可だが、IP 展開・商用化時はオリジナルに差し替え必須。
#
# ★ 設計思想 ★
# 全スプライトは hitsuji.svg シルエットを「保持」した上で、装飾だけ追加。
# 装飾の方針：
#   - モコ系：体外周に小さなフサ追加（数 px〜大量）
#   - サフォーク系：目を細く（左目を 3 px → 1 px に）
#   - ワイルド系：耳の横に角を巻かせる（小〜大）。頭上へは伸ばさない
# ベースの輪郭・顔・脚・蹄は変えないことで「同じ家系」感を保つ。
#
# 進化ツリー（spec: memory/project_mokoji_evolution_spec.md）：
#   BABY (1) → YOUNG (3 系統) → ADULT (6 品種) → SPECIAL (4 増毛 + 2 角長)
# ============================================================


def _r(s):
    """24 文字パターン (#=ON, .=OFF) を [b0, b1, b2] に変換"""
    b = [0, 0, 0]
    for i, c in enumerate(s[:24]):
        if c == '#':
            b[i >> 3] |= 1 << (7 - (i & 7))
    return b


def _img(*rows):
    return [_r(r) for r in rows]


def _flip(sp):
    """スプライトを左右反転（L→R 自動生成用）"""
    out = []
    for row in sp:
        v = (row[0] << 16) | (row[1] << 8) | row[2]
        rev = 0
        for i in range(24):
            if (v >> i) & 1:
                rev |= 1 << (23 - i)
        out.append([(rev >> 16) & 0xFF, (rev >> 8) & 0xFF, rev & 0xFF])
    return out


def _overlay(base_rows, mods):
    """base_rows に mods を適用して新しい rows tuple を返す。
    mods は (row_idx, col_idx, char) のリスト。"""
    out = [list(r) for r in base_rows]
    for r, c, ch in mods:
        out[r][c] = ch
    return tuple(''.join(row) for row in out)


